import React from 'react'
import { ShieldCheck, ShieldAlert, AlertTriangle } from 'lucide-react'

export default function FraudStatus({ result }) {
  if (!result) return null
  const isFraud = result.prediction === 1
  const pct = (result.fraud_probability * 100).toFixed(2)

  return (
    <div className={`rounded-xl p-6 animate-fadein ${isFraud ? 'animate-pulse-fraud' : ''}`}
         style={{
           background: isFraud ? '#1f0a0a' : '#071a12',
           border: `2px solid ${isFraud ? '#ef4444' : '#10b981'}`,
         }}>
      <div className="flex items-center gap-4 mb-5">
        {isFraud
          ? <ShieldAlert size={40} className="text-red-500 flex-shrink-0" />
          : <ShieldCheck size={40} className="text-emerald-500 flex-shrink-0" />
        }
        <div>
          <p className={`text-2xl font-bold ${isFraud ? 'text-red-400' : 'text-emerald-400'}`}>
            {isFraud ? '⚠ POTENTIAL FRAUD DETECTED' : '✓ LEGITIMATE TRANSACTION'}
          </p>
          <p className="text-sm mt-0.5" style={{ color: 'var(--text-secondary)' }}>
            Model: {result.display_name}
          </p>
        </div>
      </div>

      <div className="grid grid-cols-2 md:grid-cols-4 gap-4 mb-5">
        <Metric label="Fraud Probability" value={`${pct}%`} color={isFraud ? '#ef4444' : '#10b981'} />
        <Metric label="Prediction" value={result.label} color={isFraud ? '#ef4444' : '#10b981'} />
        <Metric label="Threshold" value={`${(result.threshold * 100).toFixed(0)}%`} color='#94a3b8' />
        <Metric label="Model" value={result.display_name} color='#94a3b8' />
      </div>

      {/* Probability bar */}
      <div className="mb-5">
        <div className="flex justify-between text-xs mb-1" style={{ color: 'var(--text-secondary)' }}>
          <span>Legitimate</span>
          <span>Fraud</span>
        </div>
        <div className="w-full h-3 rounded-full bg-slate-800 overflow-hidden">
          <div
            className="h-full rounded-full transition-all duration-700"
            style={{
              width: `${pct}%`,
              background: isFraud
                ? 'linear-gradient(90deg,#f97316,#ef4444)'
                : 'linear-gradient(90deg,#10b981,#059669)',
            }}
          />
        </div>
      </div>

      <div className="flex items-start gap-2 p-3 rounded-lg"
           style={{ background: '#0d1529', border: '1px solid var(--border)' }}>
        <AlertTriangle size={14} className="text-amber-400 flex-shrink-0 mt-0.5" />
        <p className="text-xs" style={{ color: 'var(--text-secondary)' }}>
          <strong className="text-amber-400">Disclaimer:</strong> This prediction is generated by an educational
          Machine Learning model. It is not a real financial authorization or guarantee of transaction safety.
        </p>
      </div>
    </div>
  )
}

function Metric({ label, value, color }) {
  return (
    <div className="rounded-lg p-3" style={{ background: '#0d1529', border: '1px solid var(--border)' }}>
      <p className="text-xs mb-1" style={{ color: 'var(--text-secondary)' }}>{label}</p>
      <p className="text-sm font-bold" style={{ color }}>{value}</p>
    </div>
  )
}
